def polar_encode(u):
    """
    极化码编码（蝶形 XOR 结构，等价于 x = u * F^{\\otimes n}）。
    """
    u = np.asarray(u, dtype=int).copy()
    N = len(u)
    n = int(np.log2(N))

    step = 1
    for _ in range(n):
        for i in range(0, N, 2 * step):
            for j in range(i, i + step):
                u[j] ^= u[j + step]
        step *= 2

    return u
