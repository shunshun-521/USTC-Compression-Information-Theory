    from channel import bpsk_modulate, compute_llr

    N, K = 64, 32
    info_idx, _, _ = ga_construction(N, K, 2.5)
    frozen_bits = np.ones(N, dtype=int)
    frozen_bits[info_idx] = 0

    rng = np.random.default_rng(0)
    errors_r = errors_n = 0
    for _ in range(100):
        u = np.zeros(N, dtype=np.int8)
        u[info_idx] = rng.integers(0, 2, size=K)
        x = polar_encode(u)
        llr = compute_llr(bpsk_modulate(x), sigma=0.01)
        if not np.array_equal(sc_decode_recursive(llr, frozen_bits)[info_idx], u[info_idx]):
            errors_r += 1
        if not np.array_equal(sc_decode(llr, frozen_bits)[info_idx], u[info_idx]):
            errors_n += 1
    print(f"Recursive SC errors: {errors_r}/100")
    print(f"Non-recursive SC errors: {errors_n}/100")
    assert errors_r == 0 and errors_n == 0
